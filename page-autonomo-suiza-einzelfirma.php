            <p>Lo primero: necesitas un permiso que te permita trabajar por cuenta propia en Suiza.</p>

            <ul>
                <li><strong>Permiso B con actividad independiente:</strong> Si eres ciudadano de la UE/AELC, puedes solicitar un permiso B para actividad independiente. Tendrás que demostrar que tu negocio es viable.</li>
                <li><strong>Permiso C:</strong> Si ya tienes residencia permanente, puedes trabajar como autónomo en Suiza sin restricciones.</li>
                <li><strong>Ciudadano suizo:</strong> Obviamente, sin restricciones.</li>
            </ul>

            <h3>Registro de tu Actividad como Autónomo en Suiza (Einzelfirma)</h3>

            <p>La forma más simple de ser autónomo en Suiza es la Einzelfirma (empresa individual). Es el equivalente al autónomo español.</p>

