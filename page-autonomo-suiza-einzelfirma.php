            <h2>7 Errores Típicos que Veo en Autónomos Hispanohablantes en Suiza</h2>

            <p>Después de 4 años y más de 500 estructuras en GNS Advisory, estos son los errores que repito cada semana en consultas. ¿Te suena alguno? Evítalos:</p>

            <ul class="error-list">
                <li>
                    <h4>Confundir "facturar desde Suiza" con "ser residente en Suiza"</h4>
                    <p>Hay quien mantiene su vida en España, abre una Einzelfirma en Suiza y piensa que ya está. Para Hacienda española sigues siendo residente y puedes acabar tributando dos veces.</p>
                </li>
                <li>
                    <h4>No inscribirse en la AVS a tiempo</h4>
                    <p>Empiezan a facturar, esperan a "tener más volumen" y luego llegan las cotizaciones atrasadas de golpe, con intereses y sanciones.</p>
                </li>
                <li>
                    <h4>Elegir un cantón caro por desconocimiento</h4>
                    <p>Se instalan en Ginebra o Zúrich porque son las ciudades famosas, sin darse cuenta de que pagan 10.000-15.000 CHF más al año que en Zug con el mismo ingreso.</p>
                </li>
                <li>
                    <h4>Traerse la mentalidad de gastos "en B" de España</h4>
                    <p>En Suiza la administración es pragmática, pero si mezclas gastos personales sin sentido en la contabilidad, te van a hacer preguntas duras.</p>
                </li>
                <li>
                    <h4>No prever que los primeros pagos de impuestos y AVS llegan con retraso</h4>
                    <p>El primer año parece "no pagas nada" y muchos se gastan el dinero. Luego, cuando llegan las liquidaciones provisionales, no tienen liquidez.</p>
                </li>
                <li>
                    <h4>No coordinar su salida fiscal de España</h4>
                    <p>Dan de alta la Einzelfirma en Suiza sin haber cerrado bien su situación en la Agencia Tributaria española (modelo 030, baja de actividad, convenio, etc.).</p>
                </li>
                <li>
                    <h4>No revisar cuándo tiene sentido pasar a GmbH</h4>
                    <p>Siguen años como Einzelfirma facturando 200.000+ CHF sin revisar que con una GmbH pagarían menos y tendrían responsabilidad limitada.</p>
                </li>
            </ul>

