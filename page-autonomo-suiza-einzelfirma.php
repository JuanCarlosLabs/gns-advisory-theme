            <h2>La Cuota de Autónomo en Suiza No Existe: Esto es lo que Pagas en Realidad</h2>

            <p>En España, ser autónomo significa pagar unos 300€ al mes (o más) de cuota a la Seguridad Social. Da igual si has facturado 10.000€ ese mes o 0€. Pagas sí o sí.</p>

            <p>En Suiza, el sistema es completamente diferente.</p>

            <p>No existe una "cuota de autónomo" como tal. Lo que pagas como autónomo en Suiza son:</p>

            <ol>
                <li><strong>Contribuciones a la seguridad social (AVS/AI/APG):</strong> Aproximadamente el 10,6% de tu beneficio neto. Pero ojo: esto se calcula sobre lo que GANAS, no es una cantidad fija.</li>
                <li><strong>IRPF suizo:</strong> Entre el 22% y el 35% según tu cantón. Progresivo, sobre tu beneficio.</li>
                <li><strong>Seguro de enfermedad:</strong> Obligatorio, entre 300-500 CHF/mes según el cantón y la cobertura.</li>
                <li><strong>IVA en Suiza:</strong> Solo si facturas más de 100.000 CHF al año. Si no llegas, no tienes obligación de cobrarlo ni declararlo.</li>
            </ol>

            <div class="highlight-box">
                <p><strong>La diferencia clave:</strong> Si un mes no facturas nada, no pagas casi nada (solo el seguro de enfermedad). En España, ese mes seguirías pagando tus 300€+ de cuota.</p>
            </div>

