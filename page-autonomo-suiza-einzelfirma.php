            <h2>Relación con España: Residencia Fiscal y Coordinación con Hacienda Española</h2>

            <p>Si eres español y te haces autónomo en Suiza, no basta con "darte de alta aquí". Hay que cerrar correctamente tu situación en España y aplicar bien el <strong>Convenio de doble imposición España-Suiza</strong> – es clave para que no acabes tributando dos veces por los mismos ingresos.</p>

            <ul>
                <li>
                    <strong>Residencia fiscal:</strong> Para dejar de ser residente fiscal en España, no es suficiente con tener una Einzelfirma en Suiza. Tienes que cumplir la regla de los 183 días y trasladar tu centro de intereses económicos y personales.
                </li>
