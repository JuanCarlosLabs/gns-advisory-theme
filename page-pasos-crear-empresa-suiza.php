            <div class="error-box">
                <h4>Error 2: El banco rechaza la apertura</h4>
                <p><strong>Coste:</strong> 2-4 semanas de retraso.</p>
                <p><strong>Solución:</strong> Prepara el justificante de origen de fondos ANTES de aplicar. Los bancos suizos son estrictos con compliance.</p>
