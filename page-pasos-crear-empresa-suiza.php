            <h2>Semana 3-4: Notaría y constitución formal</h2>

            <p>Con la carta de bloqueo del banco en mano, ya puedes ir a notaría. Este es el acto formal de constitución de la empresa.</p>

            <h3>El acto notarial: presencial o con poder apostillado</h3>

            <p><strong>Opción A - Presencial:</strong> Viajas a Suiza, te presentas ante el notario con tu pasaporte, firmas los estatutos y el acta de constitución. Duración: 30-60 minutos. Es la opción más rápida y barata.</p>

            <p><strong>Opción B - Poder apostillado:</strong> Otorgas poder notarial a tu gestor suizo ante notario español. Ese poder se apostilla (certificado de La Haya) y se envía a Suiza. Tu gestor firma en tu nombre. Añade 1-2 semanas y 300-500 EUR de coste, pero no necesitas viajar.</p>

