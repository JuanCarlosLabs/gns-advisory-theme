            <h2>Los 5 errores que matan a hispanohablantes al crear su GmbH</h2>

            <p>En 4 años asesorando a más de 150 agencias hispanohablantes, estos son los errores que más dinero cuestan. Aprende de los que ya se equivocaron:</p>

            <div class="error-box">
                <h4>Error 1: Elegir cantón por fama en vez de por números</h4>
                <p>El 70% de clientes que llegan a nosotros eligieron Zug porque "es famoso" o Ginebra porque "tiene bancos internacionales". <strong>Coste del error: 40.000-60.000 CHF al año de más.</strong></p>
                <p>Zug tiene impuestos del 11,87% pero está saturado y los costes de oficina y empleados triplican los de Nidwalden. Ginebra tiene 14,7% de impuestos más coste de vida 40% superior. Nidwalden da casi lo mismo fiscalmente con costes 30% menores.</p>
            </div>

            <div class="error-box">
                <h4>Error 2: No planificar el Exit Tax español</h4>
                <p>Si tienes patrimonio superior a 4 millones de euros y cambias residencia a Suiza sin planificación previa, Hacienda te aplica el Exit Tax: tributas por plusvalías latentes aunque no hayas vendido nada. <strong>Coste del error: 50.000-200.000 EUR de golpe.</strong></p>
                <p>La solución: planificar mínimo 12 meses antes del cambio de residencia. Vender o transformar tu SL española antes de irte. Una consultoría de 2-3k EUR te ahorra 75k+ en impuestos.</p>
            </div>

            <div class="error-box">
                <h4>Error 3: Director nominee sin sustancia real</h4>
                <p>Montar una GmbH con un director de paja que solo firma papeles mientras tú tomas todas las decisiones desde Madrid. AEAT detecta estas estructuras vacías y las desconoce. <strong>Coste del error: rechazo de la estructura + multas 50-100% de base imponible.</strong></p>
                <p>La solución: sustancia real mínima. Director residente que tome decisiones verificables, oficina física o junta directiva real, al menos 1 empleado suizo a tiempo parcial, documentación de gestión desde Suiza.</p>
            </div>

            <div class="error-box">
                <h4>Error 4: Ignorar el convenio de doble imposición los primeros 2 años</h4>
                <p>Crear la GmbH suiza pero declarar renta en ambos países sin aplicar el CDI correctamente. Resultado: pagas 12% en Suiza más 45% en España. <strong>Coste del error: 15.000-30.000 EUR de impuestos dobles.</strong></p>
                <p>La solución: asesor fiscal especializado en CDI España-Suiza, solicitar resolución fiscal previa ante AEAT, documentar el cambio de residencia antes del 31 de diciembre del año de constitución.</p>
            </div>

            <div class="error-box">
                <h4>Error 5: Pagar todo como dividendos sin optimizar</h4>
                <p>Extraer todo el beneficio como dividendos sin estructura de salario. Con solo dividendos pagas withholding del 35% más tu IRPF personal. <strong>Coste del error: 5.000-15.000 CHF al año innecesarios.</strong></p>
                <p>La estructura óptima es 50/50 salario-dividendo para bajar la carga fiscal total del 42% al 37-40%.</p>
            </div>

