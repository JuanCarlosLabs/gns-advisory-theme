            <h2>Cómo tributa una empresa suiza si vives en España</h2>

            <p>Aquí es donde la cosa se pone interesante. Y donde mucha gente se equivoca.</p>

            <h3>La empresa tributa en Suiza</h3>

            <p>Si tu empresa tiene sustancia real en Suiza (sede, admin local, decisiones tomadas allí), tributa en Suiza. Punto. El impuesto de sociedades será del 11-15% según el cantón. Eso no cambia por el hecho de que tú vivas en España.</p>

            <h3>Tú tributas en España por lo que te llevas</h3>

            <p>Aquí está el matiz importante. La empresa tributa en Suiza. Pero tú, como residente fiscal español, tributas en España por:</p>

            <ul>
                <li><strong>Dividendos:</strong> Cuando la empresa te reparte beneficios, pagas IRPF en España (19-26%). El CDI España-Suiza evita la doble imposición: Suiza retiene 5-15% y España te deduce esa cantidad.</li>
                <li><strong>Salario:</strong> Si te pagas un sueldo desde la empresa suiza, tributas en España como rendimiento del trabajo.</li>
                <li><strong>Ganancias patrimoniales:</strong> Si vendes tu participación en la empresa suiza, tributas en España.</li>
            </ul>

            <div class="highlight-box">
                <p><strong>El límite del modelo sin residencia:</strong> No puedes evitar tu IRPF personal español. Puedes optimizar la fiscalidad de la empresa (12% vs 25% en España), pero lo que tú te lleves al bolsillo sigue tributando en España. Si quieres optimizar también tu IRPF, tienes que mudarte.</p>
            </div>

