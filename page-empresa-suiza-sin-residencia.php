            <h2>Los 5 errores que arruinan una empresa suiza sin residencia</h2>

            <p>En mis años montando estructuras, he visto estos errores una y otra vez:</p>

            <div class="error-box">
                <h4>Error 1: Crear una empresa fantasma sin sustancia real</h4>
                <p>La típica: montar una GmbH con un buzón en Zug, sin oficina, sin empleados, sin actividad real en Suiza. Solo un admin fiduciario que firma papeles. Hacienda española lo ve venir a kilómetros. Reclasifican la empresa como residente en España. Pagas doble. Y multa.</p>
            </div>

            <div class="error-box">
                <h4>Error 2: Tomar todas las decisiones desde España</h4>
                <p>Si los emails importantes salen de tu Gmail español, las reuniones son siempre en Madrid, y el fiduciario solo firma lo que tú le dices... no tienes una empresa suiza. Tienes una empresa española disfrazada. La sede de dirección efectiva está donde se toman las decisiones.</p>
            </div>

            <div class="error-box">
                <h4>Error 3: No declarar la empresa en el modelo 720</h4>
                <p>Si eres residente fiscal español y tienes participaciones en una empresa extranjera, tienes que declararlas en el modelo 720 (bienes en el extranjero). No hacerlo tiene multas desproporcionadas. No es opcional.</p>
            </div>

            <div class="error-box">
                <h4>Error 4: Elegir fiduciario barato sin referencias</h4>
                <p>El fiduciario es tu cara en Suiza. Si eliges uno barato sin experiencia, sin estructura, sin reputación... te puedes encontrar con problemas de compliance, bancos que te cierran la cuenta, o peor. Vale la pena pagar por profesionalidad.</p>
            </div>

            <div class="error-box">
                <h4>Error 5: Creer que es un atajo para no pagar impuestos</h4>
                <p>No lo es. Es una estructura legítima para optimizar la fiscalidad corporativa. Pero sigues pagando impuestos en Suiza (la empresa) y en España (tú personalmente). Si alguien te vende esto como una forma de pagar cero, huye.</p>
            </div>

