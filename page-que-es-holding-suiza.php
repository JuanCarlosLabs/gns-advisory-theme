            <h2>Qué es exactamente una holding suiza y cómo funciona después de la reforma 2020</h2>

            <p>Una holding es una sociedad mercantil suiza cuyo objeto social principal es poseer participaciones en otras empresas y consolidar sus beneficios. No opera negocios propios. Solo gestiona inversiones en filiales.</p>

            <p>Desde 2020, con la reforma fiscal RFFA, la holding ya no tiene un "estatuto especial" como antes. Ahora tributa como cualquier empresa suiza. Pero aquí viene lo importante: se introdujo la <strong>deducción por participaciones</strong> que genera una exención del 95-100% de los ingresos por dividendos a nivel federal.</p>

            <p>El resultado neto es que las holdings ahora pagan impuesto ordinario, pero la carga real es igual o menor que antes de la reforma. Los cantones bajaron sus tasas para competir, y la exención federal sigue siendo brutal.</p>

