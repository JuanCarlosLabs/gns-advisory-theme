            <h2>La deducción por participaciones del Art. 69 LIFD que hace posible el ahorro</h2>

            <p>Esta es la piedra angular de todo. Según el <a href="https://www.fedlex.admin.ch/eli/cc/1991/1184_1184_1184/en" target="_blank" rel="noopener">artículo 69 de la Ley Federal de Impuesto Directo (LIFD)</a>, una sociedad suiza que posea participaciones cualificadas en otras empresas puede deducir de su renta imponible la proporción correspondiente a esos ingresos.</p>

            <p>En cristiano: si tu holding recibe 1 millón de francos en dividendos de sus filiales, y cumple los requisitos, prácticamente no paga impuesto federal sobre ese millón. Puedes consultar el texto legal completo en <a href="https://www.fedlex.admin.ch/eli/cc/1991/1184_1184_1184/en" target="_blank" rel="noopener">Fedlex (LIFD Art. 69-70)</a>.</p>

